  static double estimatePercentile(double value, double p3, double p50, double p97) {
    if (value <= p3) return 3.0;
    if (value >= p97) return 97.0;
    if (value <= p50) {
      return 3 + (value - p3) / (p50 - p3) * 47;
    } else {
      return 50 + (value - p50) / (p97 - p50) * 47;
    }
  }

  static Map<String, double> getPercentiles({
    required double ageMonths,
    required String gender,
    double? weightKg,
    double? heightCm,
    double? headCm,
  }) {
    final monthIndex = ageMonths.round().clamp(0, 24);
    final isBoy = gender.toLowerCase() != 'girl';

    final result = <String, double>{};

    if (weightKg != null) {
      final data = isBoy ? weightForAgeBoys[monthIndex] : weightForAgeGirls[monthIndex];
      result['weight'] = estimatePercentile(weightKg, data[0], data[2], data[4]);
    }

    if (heightCm != null) {
      final data = isBoy ? lengthForAgeBoys[monthIndex] : lengthForAgeGirls[monthIndex];
      result['height'] = estimatePercentile(heightCm, data[0], data[2], data[4]);
    }

    if (headCm != null) {
      final data = isBoy ? headCircBoys[monthIndex] : headCircGirls[monthIndex];
      result['head'] = estimatePercentile(headCm, data[0], data[2], data[4]);
    }

    return result;
  }
